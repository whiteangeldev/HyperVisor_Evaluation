#!/bin/bash
#
# Script: 27_final_report.sh
# Purpose: Generate comprehensive Milestone 1 report for both hypervisors
# Usage: ./27_final_report.sh
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
LOG_DIR="$PROJECT_ROOT/logs"
DOCS_DIR="$PROJECT_ROOT/docs"
REPORT_FILE="$DOCS_DIR/milestone1_final_report.md"

mkdir -p "$DOCS_DIR"

echo "========================================"
echo "Generate Final Milestone 1 Report"
echo "========================================"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

# Detect which hypervisor is running
XEN_RUNNING=false
ACRN_RUNNING=false

if command -v xl &> /dev/null && xl info &> /dev/null 2>&1; then
    XEN_RUNNING=true
fi

if [ -c /dev/acrn_hsm ] || [ -c /dev/acrn_vhm ]; then
    ACRN_RUNNING=true
fi

{
    echo "# Milestone 1 Final Report"
    echo "## Real-Time Hypervisor POC"
    echo ""
    echo "**Report Date**: $(date '+%Y-%m-%d %H:%M:%S')"
    echo ""
    echo "**Generated by**: $USER@$(hostname)"
    echo ""
    echo "**Project Phase**: Milestone 1 - Hypervisor Installation & Host Setup"
    echo ""
    echo "---"
    echo ""
    
    echo "## Executive Summary"
    echo ""
    echo "This report documents the completion of Milestone 1 for the Real-Time Hypervisor POC project."
    echo "The objective was to install and configure real-time capable hypervisors (Xen and/or Intel ACRN)"
    echo "with CPU isolation, IOMMU support, and IRQ affinity tuning for deterministic latency performance."
    echo ""
    
    echo "### Active Hypervisor Status"
    echo ""
    if [ "$XEN_RUNNING" = true ]; then
        echo "✓ **Xen Hypervisor**: ACTIVE"
    else
        echo "⚠ **Xen Hypervisor**: Not running"
    fi
    echo ""
    
    if [ "$ACRN_RUNNING" = true ]; then
        echo "✓ **Intel ACRN**: ACTIVE"
    else
        echo "⚠ **Intel ACRN**: Not running"
    fi
    echo ""
    echo "---"
    echo ""
    
    echo "## 1. Hardware and System Information"
    echo ""
    echo "### 1.1 CPU Information"
    echo ""
    echo '```'
    echo "Processor: $(grep "model name" /proc/cpuinfo | head -1 | cut -d: -f2 | xargs)"
    echo "CPU Cores: $(nproc)"
    echo "Architecture: $(uname -m)"
    lscpu | grep -E "^(Vendor ID|CPU family|Model|Stepping|Virtualization):"
    echo '```'
    echo ""
    
    echo "### 1.2 Memory"
    echo ""
    TOTAL_MEM_GB=$(free -g | grep "Mem:" | awk '{print $2}')
    echo "Total Memory: ${TOTAL_MEM_GB}GB"
    echo ""
    
    echo "### 1.3 Operating System"
    echo ""
    echo '```'
    cat /etc/os-release | grep -E "^(PRETTY_NAME|VERSION)="
    echo "Kernel: $(uname -r)"
    echo '```'
    echo ""
    
    echo "### 1.4 Network Interfaces"
    echo ""
    echo '```'
    lspci -nn | grep -i ethernet
    echo '```'
    echo ""
    echo "---"
    echo ""
    
    echo "## 2. Kernel Configuration and Isolation"
    echo ""
    echo "### 2.1 Current Kernel Command Line"
    echo ""
    echo '```'
    cat /proc/cmdline
    echo '```'
    echo ""
    
    echo "### 2.2 Isolation Configuration"
    echo ""
    echo "| Parameter | Status | Value | Purpose |"
    echo "|-----------|--------|-------|---------|"
    
    if grep -q "isolcpus=" /proc/cmdline; then
        VALUE=$(grep -o "isolcpus=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| isolcpus | ✓ | $VALUE | CPU isolation from general scheduler |"
    else
        echo "| isolcpus | ✗ | - | Not configured |"
    fi
    
    if grep -q "nohz_full=" /proc/cmdline; then
        VALUE=$(grep -o "nohz_full=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| nohz_full | ✓ | $VALUE | Disable scheduler tick on isolated CPUs |"
    else
        echo "| nohz_full | ✗ | - | Not configured |"
    fi
    
    if grep -q "rcu_nocbs=" /proc/cmdline; then
        VALUE=$(grep -o "rcu_nocbs=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| rcu_nocbs | ✓ | $VALUE | Offload RCU callbacks from isolated CPUs |"
    else
        echo "| rcu_nocbs | ✗ | - | Not configured |"
    fi
    
    if grep -qE "(intel_iommu=on|amd_iommu=on)" /proc/cmdline; then
        VALUE=$(grep -oE "(intel_iommu|amd_iommu)=[^ ]*" /proc/cmdline)
        echo "| IOMMU | ✓ | $VALUE | Enable IOMMU/VT-d for device passthrough |"
    else
        echo "| IOMMU | ✗ | - | Not configured |"
    fi
    
    if grep -q "idle=poll" /proc/cmdline; then
        echo "| idle | ✓ | poll | Polling idle loop (lowest latency) |"
    elif grep -q "idle=mwait" /proc/cmdline; then
        echo "| idle | ✓ | mwait | MWAIT idle (balanced) |"
    else
        echo "| idle | ⚠ | default | Using default idle |"
    fi
    
    echo ""
    
    echo "### 2.3 CPU Isolation Verification"
    echo ""
    if [ -f /sys/devices/system/cpu/isolated ]; then
        ISOLATED=$(cat /sys/devices/system/cpu/isolated)
        if [ -n "$ISOLATED" ]; then
            echo "✓ **Isolated CPUs**: $ISOLATED"
        else
            echo "⚠ **Warning**: No CPUs are isolated (check kernel parameters)"
        fi
    else
        echo "⚠ **Warning**: Isolation status not available"
    fi
    echo ""
    
    if [ -f /sys/devices/system/cpu/nohz_full ]; then
        NOHZ=$(cat /sys/devices/system/cpu/nohz_full)
        if [ -n "$NOHZ" ]; then
            echo "✓ **NO_HZ Full CPUs**: $NOHZ"
        fi
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 3. IOMMU Configuration"
    echo ""
    
    if [ -d /sys/kernel/iommu_groups ]; then
        GROUP_COUNT=$(find /sys/kernel/iommu_groups -maxdepth 1 -type d | wc -l)
        GROUP_COUNT=$((GROUP_COUNT - 1))
        
        if [ $GROUP_COUNT -gt 0 ]; then
            echo "✓ **IOMMU Status**: Enabled and operational"
            echo ""
            echo "✓ **IOMMU Groups**: $GROUP_COUNT groups detected"
            echo ""
            
            echo "### 3.1 Device Passthrough Candidates"
            echo ""
            echo "Single-device IOMMU groups (ideal for passthrough):"
            echo ""
            echo '```'
            for group in /sys/kernel/iommu_groups/*; do
                if [ -d "$group" ]; then
                    group_num=$(basename "$group")
                    device_count=$(find "$group/devices" -maxdepth 1 -type l | wc -l)
                    
                    if [ $device_count -eq 1 ]; then
                        echo "Group $group_num:"
                        for device in "$group"/devices/*; do
                            dev_path=$(basename "$device")
                            lspci -nn -s "$dev_path" 2>/dev/null | sed 's/^/  /'
                        done
                    fi
                fi
            done
            echo '```'
            echo ""
        else
            echo "⚠ **IOMMU Status**: Enabled but no groups found"
            echo ""
        fi
    else
        echo "✗ **IOMMU Status**: Not enabled"
        echo ""
    fi
    
    echo "---"
    echo ""
    
    echo "## 4. Hypervisor Status"
    echo ""
    
    # Xen Section
    echo "### 4.1 Xen Hypervisor"
    echo ""
    
    if [ "$XEN_RUNNING" = true ]; then
        echo "✓ **Status**: RUNNING"
        echo ""
        
        echo "**Version Information**:"
        echo '```'
        xl info | grep -E "^(release|version|xen_caps|xen_major|xen_minor):" | head -10
        echo '```'
        echo ""
        
        echo "**Scheduler**:"
        echo '```'
        xl info | grep -i sched
        echo '```'
        echo ""
        
        SCHED=$(xl info 2>/dev/null | grep "^sched_id" | awk '{print $NF}' || echo "unknown")
        if [ "$SCHED" = "rtds" ] || xl info 2>/dev/null | grep -qi "rtds"; then
            echo "✓ **RT Scheduler**: Real-Time Deferrable Server (RTDS) active"
        else
            echo "⚠ **RT Scheduler**: Using $SCHED (not RT optimized)"
        fi
        echo ""
        
        echo "**Dom0 Configuration**:"
        echo '```'
        xl list 2>/dev/null | head -5
        echo ""
        xl vcpu-list 0 2>/dev/null | head -10
        echo '```'
        echo ""
        
        echo "**CPU Pools** (for CPU partitioning):"
        echo '```'
        xl cpupool-list 2>/dev/null || echo "No CPU pools configured"
        echo '```'
        echo ""
    else
        echo "⚠ **Status**: Not running"
        echo ""
        
        if command -v xl &> /dev/null; then
            echo "Xen tools are installed but hypervisor is not active."
            echo "System may need to boot into Xen kernel."
        else
            echo "Xen not installed on this system."
        fi
        echo ""
    fi
    
    # ACRN Section
    echo "### 4.2 Intel ACRN"
    echo ""
    
    if [ "$ACRN_RUNNING" = true ]; then
        echo "✓ **Status**: RUNNING"
        echo ""
        
        echo "**Device Nodes**:"
        echo '```'
        ls -la /dev/acrn* 2>/dev/null
        echo '```'
        echo ""
        
        echo "**Kernel Modules**:"
        echo '```'
        lsmod | grep acrn
        echo '```'
        echo ""
        
        if command -v acrnctl &> /dev/null; then
            echo "**Running VMs**:"
            echo '```'
            acrnctl list 2>&1 || echo "No VMs currently running"
            echo '```'
            echo ""
        fi
        
        if command -v acrn-dm &> /dev/null; then
            echo "**Tools Installed**:"
            echo '```'
            echo "Device Model: $(which acrn-dm)"
            echo "Control Tool: $(which acrnctl 2>/dev/null || echo 'not found')"
            echo "Log Tool: $(which acrnlog 2>/dev/null || echo 'not found')"
            echo '```'
            echo ""
        fi
    else
        echo "⚠ **Status**: Not running"
        echo ""
        
        if [ -f /usr/bin/acrn-dm ]; then
            echo "ACRN tools are installed but hypervisor is not active."
            echo "System may need to boot into ACRN kernel from GRUB."
        else
            echo "ACRN not installed on this system."
        fi
        echo ""
    fi
    
    echo "---"
    echo ""
    
    echo "## 5. IRQ Affinity Configuration"
    echo ""
    
    echo "### 5.1 IRQ Balancer Status"
    echo ""
    if systemctl is-enabled irqbalance &>/dev/null; then
        if systemctl is-active irqbalance &>/dev/null; then
            echo "⚠ **irqbalance**: Running (should be disabled for RT)"
        else
            echo "✓ **irqbalance**: Stopped (disabled for RT)"
        fi
    else
        echo "✓ **irqbalance**: Disabled"
    fi
    echo ""
    
    echo "### 5.2 IRQ Distribution Sample"
    echo ""
    echo "First 15 IRQs and their CPU affinity:"
    echo ""
    echo "| IRQ | CPUs | Device |"
    echo "|-----|------|--------|"
    
    for irq in $(ls /proc/irq/ | grep "^[0-9]" | sort -n | head -15); do
        if [ -f "/proc/irq/$irq/smp_affinity_list" ]; then
            affinity=$(cat "/proc/irq/$irq/smp_affinity_list" 2>/dev/null || echo "N/A")
            
            if [ -f "/proc/irq/$irq/actions" ]; then
                actions=$(cat "/proc/irq/$irq/actions" 2>/dev/null | tr '\n' ' ' | cut -c1-30)
            else
                actions=""
            fi
            
            echo "| $irq | $affinity | ${actions:-N/A} |"
        fi
    done
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 6. Milestone 1 Acceptance Criteria"
    echo ""
    
    TOTAL_CHECKS=0
    PASSED_CHECKS=0
    
    echo "### 6.1 Required Deliverables"
    echo ""
    
    echo "#### 6.1.1 Bootable Hypervisor with Isolation"
    ((TOTAL_CHECKS++))
    if [ "$XEN_RUNNING" = true ] || [ "$ACRN_RUNNING" = true ]; then
        if grep -q "isolcpus" /proc/cmdline && [ -f /sys/devices/system/cpu/isolated ]; then
            ISOLATED=$(cat /sys/devices/system/cpu/isolated)
            if [ -n "$ISOLATED" ]; then
                echo "✓ **PASS**: Hypervisor running with CPU isolation (CPUs $ISOLATED)"
                ((PASSED_CHECKS++))
            else
                echo "⚠ **PARTIAL**: Hypervisor running but isolation not verified"
            fi
        else
            echo "⚠ **PARTIAL**: Hypervisor running but isolation parameters missing"
        fi
    else
        echo "✗ **FAIL**: No hypervisor currently running"
    fi
    echo ""
    
    echo "#### 6.1.2 IOMMU/VT-d Enabled"
    ((TOTAL_CHECKS++))
    if grep -qE "(intel_iommu=on|amd_iommu=on)" /proc/cmdline && [ -d /sys/kernel/iommu_groups ]; then
        GROUP_COUNT=$(find /sys/kernel/iommu_groups -maxdepth 1 -type d | wc -l)
        GROUP_COUNT=$((GROUP_COUNT - 1))
        if [ $GROUP_COUNT -gt 0 ]; then
            echo "✓ **PASS**: IOMMU enabled with $GROUP_COUNT groups"
            ((PASSED_CHECKS++))
        else
            echo "⚠ **PARTIAL**: IOMMU enabled but no groups enumerated"
        fi
    else
        echo "✗ **FAIL**: IOMMU not properly enabled"
    fi
    echo ""
    
    echo "#### 6.1.3 CPU Pinning and Isolation"
    ((TOTAL_CHECKS++))
    if grep -q "isolcpus" /proc/cmdline && grep -q "nohz_full" /proc/cmdline && grep -q "rcu_nocbs" /proc/cmdline; then
        echo "✓ **PASS**: Complete isolation parameters configured"
        ((PASSED_CHECKS++))
    else
        echo "✗ **FAIL**: Isolation parameters incomplete"
    fi
    echo ""
    
    echo "#### 6.1.4 IRQ Affinity Configuration"
    ((TOTAL_CHECKS++))
    if systemctl is-active irqbalance &>/dev/null; then
        echo "⚠ **PARTIAL**: IRQ affinity set but irqbalance still running"
    elif systemctl is-enabled irqbalance &>/dev/null; then
        echo "⚠ **PARTIAL**: irqbalance disabled but not stopped"
    else
        echo "✓ **PASS**: irqbalance disabled, IRQ affinity can be managed"
        ((PASSED_CHECKS++))
    fi
    echo ""
    
    echo "#### 6.1.5 Documentation and Scripts"
    ((TOTAL_CHECKS++))
    SCRIPT_COUNT=$(ls "$SCRIPT_DIR"/*.sh 2>/dev/null | wc -l)
    LOG_COUNT=$(ls "$LOG_DIR"/*.log 2>/dev/null | wc -l)
    
    if [ $SCRIPT_COUNT -ge 15 ] && [ $LOG_COUNT -ge 3 ]; then
        echo "✓ **PASS**: Scripts ($SCRIPT_COUNT) and logs ($LOG_COUNT) present"
        ((PASSED_CHECKS++))
    else
        echo "⚠ **PARTIAL**: Documentation incomplete (scripts: $SCRIPT_COUNT, logs: $LOG_COUNT)"
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 7. Final Assessment"
    echo ""
    
    PERCENTAGE=$((PASSED_CHECKS * 100 / TOTAL_CHECKS))
    echo "### Acceptance Score"
    echo ""
    echo "**Result**: $PASSED_CHECKS / $TOTAL_CHECKS criteria passed ($PERCENTAGE%)"
    echo ""
    
    if [ $PERCENTAGE -ge 80 ]; then
        echo "### ✓✓✓ Milestone 1: **PASS** ✓✓✓"
        echo ""
        echo "The system successfully meets Milestone 1 acceptance criteria."
        echo "The hypervisor is operational with proper CPU isolation, IOMMU support,"
        echo "and documentation. The system is ready for Milestone 2."
        VERDICT="PASS"
    elif [ $PERCENTAGE -ge 60 ]; then
        echo "### ⚠⚠⚠ Milestone 1: **CONDITIONAL PASS** ⚠⚠⚠"
        echo ""
        echo "The system meets most Milestone 1 criteria but has some gaps."
        echo "Review the failed checks above and address before proceeding to Milestone 2."
        VERDICT="CONDITIONAL"
    else
        echo "### ✗✗✗ Milestone 1: **INCOMPLETE** ✗✗✗"
        echo ""
        echo "The system does not meet minimum Milestone 1 criteria."
        echo "Significant configuration work is needed before proceeding."
        VERDICT="FAIL"
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 8. Next Steps"
    echo ""
    
    if [ "$VERDICT" = "PASS" ] || [ "$VERDICT" = "CONDITIONAL" ]; then
        echo "### Milestone 2: VM Configuration and VFIO Passthrough"
        echo ""
        echo "1. **Create RT Guest VM**"
        echo "   - Install PREEMPT_RT Linux or Xenomai"
        echo "   - Pin to isolated CPUs"
        echo "   - Configure for real-time workloads"
        echo ""
        echo "2. **Create GPOS Guest VM**"
        echo "   - Install Windows or Linux GPOS"
        echo "   - Configure for stress testing"
        echo "   - Assign non-isolated CPUs"
        echo ""
        echo "3. **Configure VFIO Device Passthrough**"
        echo "   - Identify devices in isolated IOMMU groups"
        echo "   - Pass through NIC to RT VM"
        echo "   - Pass through USB/PCIe devices as needed"
        echo ""
        echo "4. **Performance Validation**"
        echo "   - Run cyclictest on RT VM"
        echo "   - Apply stress-ng on GPOS VM"
        echo "   - Measure latency under load"
        echo "   - Collect traces with ftrace/perf"
        echo ""
    else
        echo "### Complete Milestone 1 Requirements"
        echo ""
        echo "1. Review failed acceptance criteria above"
        echo "2. Re-run configuration scripts as needed"
        echo "3. Ensure hypervisor boots correctly"
        echo "4. Verify IOMMU and isolation parameters"
        echo "5. Re-run verification scripts"
        echo "6. Generate report again"
        echo ""
    fi
    
    echo "---"
    echo ""
    
    echo "## 9. Log Files and Artifacts"
    echo ""
    echo "### 9.1 Logs Generated"
    echo ""
    if [ -d "$LOG_DIR" ]; then
        for log in "$LOG_DIR"/*.log; do
            if [ -f "$log" ]; then
                filename=$(basename "$log")
                size=$(du -h "$log" | cut -f1)
                lines=$(wc -l < "$log" 2>/dev/null || echo "0")
                echo "- **$filename** ($size, $lines lines)"
            fi
        done
    else
        echo "No logs found"
    fi
    echo ""
    
    echo "### 9.2 Configuration Files"
    echo ""
    if [ -d "$PROJECT_ROOT/configs" ]; then
        find "$PROJECT_ROOT/configs" -type f 2>/dev/null | while read -r file; do
            filename=$(basename "$file")
            size=$(du -h "$file" | cut -f1)
            echo "- **$filename** ($size)"
        done
    else
        echo "No configuration files found"
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 10. Recommendations"
    echo ""
    
    if [ "$XEN_RUNNING" = true ]; then
        echo "### Xen-Specific Recommendations"
        echo ""
        echo "- Consider creating CPU pools for strict CPU partitioning"
        echo "- Use xl cpupool-cpu-remove/add to dedicate physical CPUs to RT domains"
        echo "- Configure xl cpupool-numa-split for NUMA-aware partitioning"
        echo "- Use rtds scheduler parameters: period, budget for RT VMs"
        echo ""
    fi
    
    if [ "$ACRN_RUNNING" = true ]; then
        echo "### ACRN-Specific Recommendations"
        echo ""
        echo "- Use --lapic_pt flag for LAPIC passthrough to RT VMs"
        echo "- Enable --rtvm flag for real-time optimizations"
        echo "- Configure Cache Allocation Technology (CAT) if CPU supports it"
        echo "- Use --virtio_poll for lowest I/O latency"
        echo ""
    fi
    
    echo "### General Recommendations"
    echo ""
    echo "- Disable unnecessary system services to reduce CPU wake-ups"
    echo "- Consider using cpupower to set performance governor"
    echo "- Monitor IRQ distribution: watch -n1 'cat /proc/interrupts'"
    echo "- Use tuna for CPU isolation verification"
    echo "- Test with cyclictest baseline before adding VMs"
    echo ""
    
    echo "---"
    echo ""
    echo "*Report generated by: $(basename "$0")*"
    echo ""
    echo "*Generation time: $(date '+%Y-%m-%d %H:%M:%S')*"
    echo ""
    
} > "$REPORT_FILE"

echo "✓ Final Milestone 1 report generated"
echo "✓ Output saved to: $REPORT_FILE"
echo ""

# Display verdict
echo "=========================================="
if grep -q "Milestone 1: \*\*PASS\*\*" "$REPORT_FILE"; then
    echo "✓✓✓ MILESTONE 1: PASS ✓✓✓"
elif grep -q "Milestone 1: \*\*CONDITIONAL PASS\*\*" "$REPORT_FILE"; then
    echo "⚠⚠⚠ MILESTONE 1: CONDITIONAL PASS ⚠⚠⚠"
else
    echo "✗✗✗ MILESTONE 1: INCOMPLETE ✗✗✗"
fi
echo "=========================================="
echo ""

# Display summary
grep "Result:" "$REPORT_FILE" | grep -v "^#"
echo ""
echo "View full report:"
echo "  cat $REPORT_FILE"
echo ""
echo "Or convert to PDF:"
echo "  pandoc $REPORT_FILE -o ${REPORT_FILE%.md}.pdf"
echo ""

