#!/bin/bash
#
# Script: 23_configure_acrn.sh
# Purpose: Generate ACRN configuration for RT setup
# Usage: ./23_configure_acrn.sh
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
CONFIG_DIR="$PROJECT_ROOT/configs"
ACRN_CONFIG="$CONFIG_DIR/acrn_rt.conf"

mkdir -p "$CONFIG_DIR"

echo "========================================"
echo "Configure Intel ACRN for RT"
echo "========================================"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

# Detect system configuration
TOTAL_CPUS=$(nproc)
echo "Detected CPUs: $TOTAL_CPUS"

# CPU allocation strategy for ACRN:
# - Service OS (SOS): CPUs 0-3 (management VM)
# - RT User OS (UOS): CPUs 4-5 (real-time VM)
# - GPOS User OS (UOS): CPUs 6-7 (general purpose VM)

if [ "$TOTAL_CPUS" -ge 8 ]; then
    SOS_CPUS="0,1,2,3"
    RT_CPUS="4,5"
    GPOS_CPUS="6,7"
elif [ "$TOTAL_CPUS" -ge 6 ]; then
    SOS_CPUS="0,1"
    RT_CPUS="2,3"
    GPOS_CPUS="4,5"
elif [ "$TOTAL_CPUS" -ge 4 ]; then
    SOS_CPUS="0"
    RT_CPUS="1,2"
    GPOS_CPUS="3"
else
    echo "⚠ Warning: Only $TOTAL_CPUS CPUs detected. Recommend 8+ for proper isolation."
    SOS_CPUS="0"
    RT_CPUS="1"
    GPOS_CPUS="2"
fi

echo "Service OS CPUs: $SOS_CPUS"
echo "RT VM CPUs: $RT_CPUS"
echo "GPOS VM CPUs: $GPOS_CPUS"
echo ""

{
    echo "# ACRN Real-Time Configuration"
    echo "# Generated: $(date '+%Y-%m-%d %H:%M:%S')"
    echo "# System: $(hostname)"
    echo "# Total CPUs: $TOTAL_CPUS"
    echo ""
    echo "# CPU Allocation:"
    echo "# - Service OS (SOS): $SOS_CPUS"
    echo "# - RT User OS (UOS): $RT_CPUS"
    echo "# - GPOS User OS (UOS): $GPOS_CPUS"
    echo ""
    echo "# ============================================"
    echo "# Service OS (Service VM) Configuration"
    echo "# ============================================"
    echo ""
    echo "[service_os]"
    echo "name = Service_VM"
    echo "vcpu_num = $(echo "$SOS_CPUS" | tr ',' '\n' | wc -l)"
    echo "vcpu_affinity = $SOS_CPUS"
    echo "memory_size = 2048M"
    echo ""
    echo "# Service OS manages device passthrough to User OSes"
    echo "# It runs on housekeeping CPUs to avoid RT interference"
    echo ""
    echo "# ============================================"
    echo "# RT User OS (Real-Time VM) Configuration"
    echo "# ============================================"
    echo ""
    echo "[rt_uos]"
    echo "name = RT_VM"
    echo "vcpu_num = $(echo "$RT_CPUS" | tr ',' '\n' | wc -l)"
    echo "vcpu_affinity = $RT_CPUS"
    echo "memory_size = 2048M"
    echo ""
    echo "# RT VM Characteristics:"
    echo "# - Dedicated CPUs: $RT_CPUS"
    echo "# - CPU pinning: strict 1:1 vCPU to pCPU"
    echo "# - Memory: locked and pre-allocated"
    echo "# - Cache allocation: dedicated cache ways (if supported)"
    echo "# - Interrupts: routed to Service OS, not RT CPUs"
    echo ""
    echo "# Launch Script Parameters for RT VM:"
    echo "# acrn-dm -m 2048M \\"
    echo "#   --lapic_pt \\"
    echo "#   --rtvm \\"
    echo "#   --virtio_poll 1000000 \\"
    echo "#   --cpu_affinity $RT_CPUS \\"
    echo "#   RT_VM"
    echo ""
    echo "# ============================================"
    echo "# GPOS User OS (General Purpose VM) Configuration"
    echo "# ============================================"
    echo ""
    echo "[gpos_uos]"
    echo "name = GPOS_VM"
    echo "vcpu_num = $(echo "$GPOS_CPUS" | tr ',' '\n' | wc -l)"
    echo "vcpu_affinity = $GPOS_CPUS"
    echo "memory_size = 4096M"
    echo ""
    echo "# GPOS VM Characteristics:"
    echo "# - Dedicated CPUs: $GPOS_CPUS"
    echo "# - Standard virtualization features"
    echo "# - Can handle interrupts and I/O load"
    echo ""
    echo "# ============================================"
    echo "# Device Passthrough Configuration"
    echo "# ============================================"
    echo ""
    echo "# Network devices for passthrough:"
    echo "# Run 'lspci -nn | grep Ethernet' to identify devices"
    echo ""
    lspci -nn | grep -i ethernet | sed 's/^/# /'
    echo ""
    echo "# USB devices for passthrough:"
    echo "# Run 'lspci -nn | grep USB' to identify devices"
    echo ""
    lspci -nn | grep -i usb | sed 's/^/# /' || echo "# No USB controllers found via PCI"
    echo ""
    echo "# Example device passthrough to RT VM:"
    echo "# --passthru <bus>/<dev>/<func>,<vendor>:<device>"
    echo ""
    echo "# ============================================"
    echo "# Real-Time Optimization Parameters"
    echo "# ============================================"
    echo ""
    echo "# ACRN RT Features:"
    echo "# 1. LAPIC Passthrough (--lapic_pt)"
    echo "#    - Direct local APIC access for lowest latency"
    echo "#"
    echo "# 2. RT VM Flag (--rtvm)"
    echo "#    - Enables real-time optimizations"
    echo "#    - Disables EPT violation handling"
    echo "#    - Pre-allocates and locks memory"
    echo "#"
    echo "# 3. Virtio Polling (--virtio_poll)"
    echo "#    - Reduces I/O latency via polling instead of interrupts"
    echo "#"
    echo "# 4. CPU Affinity (--cpu_affinity)"
    echo "#    - 1:1 vCPU to pCPU pinning"
    echo "#"
    echo "# 5. Cache Allocation Technology (CAT)"
    echo "#    - Dedicate cache ways to RT VM"
    echo "#    - Prevent cache pollution from other VMs"
    echo ""
    echo "# ============================================"
    echo "# Kernel Parameters for Service OS"
    echo "# ============================================"
    echo ""
    echo "# Add to GRUB kernel command line:"
    echo "# module2 /boot/vmlinuz root=... rw \\"
    echo "#   isolcpus=$RT_CPUS,$GPOS_CPUS \\"
    echo "#   nohz_full=$RT_CPUS \\"
    echo "#   rcu_nocbs=$RT_CPUS \\"
    echo "#   nosoftlockup \\"
    echo "#   intel_idle.max_cstate=0 \\"
    echo "#   processor.max_cstate=1 \\"
    echo "#   idle=poll"
    echo ""
    echo "# ============================================"
    echo "# Validation Commands"
    echo "# ============================================"
    echo ""
    echo "# After booting ACRN:"
    echo "# 1. Check ACRN status: ls /dev/acrn*"
    echo "# 2. View hypervisor log: acrnlog -t"
    echo "# 3. List VMs: acrnctl list"
    echo "# 4. Check Service OS CPU isolation:"
    echo "#    cat /sys/devices/system/cpu/isolated"
    echo ""
    
} > "$ACRN_CONFIG"

echo "✓ ACRN configuration generated successfully"
echo "✓ Output saved to: $ACRN_CONFIG"
echo ""
echo "Configuration summary:"
echo "  Service OS CPUs: $SOS_CPUS"
echo "  RT VM CPUs: $RT_CPUS"
echo "  GPOS VM CPUs: $GPOS_CPUS"
echo ""
echo "Review configuration: cat $ACRN_CONFIG"
echo ""
echo "Next steps:"
echo "1. Review GRUB entry: sudo cat /etc/grub.d/40_custom_acrn"
echo "2. Edit if needed: sudo nano /etc/grub.d/40_custom_acrn"
echo "3. Reboot and select ACRN from GRUB menu"
echo "4. Verify ACRN: ./scripts/24_verify_acrn.sh"
echo ""

