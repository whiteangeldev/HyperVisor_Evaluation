#!/bin/bash
#
# Script: 11_generate_irq_script.sh
# Purpose: Generate script to set IRQ affinity to housekeeping CPUs
# Usage: ./11_generate_irq_script.sh
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
OUTPUT_SCRIPT="$SCRIPT_DIR/set_irq_affinity.sh"

echo "========================================"
echo "Generate IRQ Affinity Script"
echo "========================================"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

# Detect CPU configuration
TOTAL_CPUS=$(nproc)
echo "Total CPUs: $TOTAL_CPUS"

# Determine housekeeping CPUs (non-isolated)
# In Xen Dom0: Dom0 VCPUs are the housekeeping CPUs
# Use ALL Dom0 CPUs for IRQ handling
if [ "$TOTAL_CPUS" -ge 8 ]; then
    # 8+ CPUs: Use all for housekeeping
    HOUSEKEEPING_CPUS="0,1,2,3,4,5,6,7"
    HOUSEKEEPING_MASK="ff"  # Binary: 1111 1111 (CPUs 0-7)
elif [ "$TOTAL_CPUS" = 4 ]; then
    # 4 CPUs (Dom0): Use all 4 for IRQs
    HOUSEKEEPING_CPUS="0,1,2,3"
    HOUSEKEEPING_MASK="0f"  # Binary: 0000 1111 (CPUs 0-3)
elif [ "$TOTAL_CPUS" -ge 2 ]; then
    # 2-3 CPUs: Use all
    HOUSEKEEPING_CPUS="0,1"
    HOUSEKEEPING_MASK="03"  # Binary: 0000 0011 (CPUs 0-1)
else
    # 1 CPU
    HOUSEKEEPING_CPUS="0"
    HOUSEKEEPING_MASK="01"  # Binary: 0000 0001 (CPU 0)
fi

echo "Housekeeping CPUs: $HOUSEKEEPING_CPUS"
echo "Affinity Mask: $HOUSEKEEPING_MASK"
echo ""

# Generate the IRQ affinity script
cat > "$OUTPUT_SCRIPT" << 'SCRIPT_HEADER'
#!/bin/bash
#
# Script: set_irq_affinity.sh
# Purpose: Set all IRQ affinities to housekeeping CPUs
# Generated by: 11_generate_irq_script.sh
# Usage: sudo ./set_irq_affinity.sh
# ⚠️  REQUIRES ROOT PRIVILEGES
#

# Note: NOT using 'set -e' because some IRQs will fail (hardware-locked)
# and that's expected behavior, not a script failure

# Check if running as root
if [ "$EUID" -ne 0 ]; then
    echo "❌ ERROR: This script must be run as root"
    echo "Usage: sudo $0"
    exit 1
fi

SCRIPT_HEADER

# Add configuration section
cat >> "$OUTPUT_SCRIPT" << EOF

# Configuration
HOUSEKEEPING_CPUS="${HOUSEKEEPING_CPUS}"
HOUSEKEEPING_MASK="${HOUSEKEEPING_MASK}"

echo "========================================"
echo "Set IRQ Affinity"
echo "========================================"
echo "Timestamp: \$(date '+%Y-%m-%d %H:%M:%S')"
echo "Target CPUs: \${HOUSEKEEPING_CPUS}"
echo "Affinity Mask: \${HOUSEKEEPING_MASK}"
echo ""

# Set default SMP affinity
if [ -f /proc/irq/default_smp_affinity ]; then
    echo "\${HOUSEKEEPING_MASK}" > /proc/irq/default_smp_affinity
    echo "✓ Set default_smp_affinity to \${HOUSEKEEPING_MASK}"
fi

# Process all IRQs
success_count=0
fail_count=0
skip_count=0

for irq_dir in /proc/irq/*; do
    if [ -d "\$irq_dir" ] && [ "\$(basename "\$irq_dir")" != "default_smp_affinity" ]; then
        irq_num=\$(basename "\$irq_dir")
        
        # Skip non-numeric directories
        if ! [[ "\$irq_num" =~ ^[0-9]+\$ ]]; then
            continue
        fi
        
        # Skip if no affinity file
        if [ ! -f "\$irq_dir/smp_affinity" ]; then
            skip_count=\$((skip_count + 1))
            continue
        fi
        
        # Get IRQ name
        if [ -f "\$irq_dir/actions" ]; then
            irq_name=\$(cat "\$irq_dir/actions" 2>/dev/null | head -1 | tr '\n' ' ')
        else
            irq_name="unknown"
        fi
        
        # Try to set affinity
        if echo "\${HOUSEKEEPING_MASK}" > "\$irq_dir/smp_affinity" 2>/dev/null; then
            echo "✓ IRQ \${irq_num}: \${irq_name}"
            success_count=\$((success_count + 1))
        else
            echo "⚠ IRQ \${irq_num}: Failed (may be hardware-specific)"
            fail_count=\$((fail_count + 1))
        fi
    fi
done

echo ""
echo "========================================"
echo "Summary"
echo "========================================"
echo "Successfully set: \${success_count}"
echo "Failed to set: \${fail_count}"
echo "Skipped: \${skip_count}"
echo ""

# Verify a few IRQs
echo "Verification (first 5 IRQs):"
count=0
for irq_dir in /proc/irq/*/smp_affinity_list; do
    if [ -f "\$irq_dir" ] && [ \$count -lt 5 ]; then
        irq_num=\$(echo "\$irq_dir" | sed 's|.*/irq/\([0-9]*\)/.*|\1|')
        affinity=\$(cat "\$irq_dir" 2>/dev/null || echo "N/A")
        echo "  IRQ \${irq_num}: CPU \${affinity}"
        count=\$((count + 1))
    fi
done

echo ""
if [ \$fail_count -gt 0 ]; then
    echo "✓ IRQ affinity configuration completed with some expected failures"
    echo "  (Hardware-locked IRQs cannot be moved - this is normal)"
else
    echo "✓ IRQ affinity configuration completed successfully"
fi
echo ""

# Exit successfully even if some IRQs failed to move
exit 0
EOF

chmod +x "$OUTPUT_SCRIPT"

echo "✓ IRQ affinity script generated"
echo "✓ Output saved to: $OUTPUT_SCRIPT"
echo "✓ Script is executable"
echo ""
echo "Configuration:"
echo "  - Target CPUs: $HOUSEKEEPING_CPUS"
echo "  - Affinity Mask: $HOUSEKEEPING_MASK"
echo ""
echo "Next steps:"
echo "1. Stop irqbalance: sudo systemctl stop irqbalance"
echo "2. Run script: sudo $OUTPUT_SCRIPT"
echo ""

