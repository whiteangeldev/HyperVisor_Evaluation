#!/bin/bash
#
# Script: 17_generate_report.sh
# Purpose: Generate comprehensive Milestone 1 completion report
# Usage: ./17_generate_report.sh
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
LOG_DIR="$PROJECT_ROOT/logs"
DOCS_DIR="$PROJECT_ROOT/docs"
REPORT_FILE="$DOCS_DIR/milestone1_report.md"

mkdir -p "$DOCS_DIR"

echo "========================================"
echo "Generate Milestone 1 Report"
echo "========================================"
echo "Timestamp: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

{
    echo "# Milestone 1 Completion Report"
    echo ""
    echo "**Project**: Real-Time Hypervisor POC"
    echo ""
    echo "**Report Date**: $(date '+%Y-%m-%d %H:%M:%S')"
    echo ""
    echo "**Generated by**: $USER@$(hostname)"
    echo ""
    echo "---"
    echo ""
    
    echo "## Executive Summary"
    echo ""
    echo "This report documents the completion of Milestone 1: Hypervisor Installation & Host Setup."
    echo "The objective was to install and configure a real-time capable hypervisor with CPU isolation,"
    echo "IOMMU support, and IRQ affinity tuning for deterministic latency performance."
    echo ""
    echo "---"
    echo ""
    
    echo "## 1. System Configuration"
    echo ""
    echo "### 1.1 Hardware Information"
    echo ""
    echo '```'
    lscpu | head -15
    echo '```'
    echo ""
    
    echo "### 1.2 Operating System"
    echo ""
    echo '```'
    cat /etc/os-release | grep -E "^(NAME|VERSION|ID|VERSION_ID)="
    echo ""
    echo "Kernel: $(uname -r)"
    echo '```'
    echo ""
    
    echo "### 1.3 Network Interfaces"
    echo ""
    echo '```'
    ip link show | grep -E "^[0-9]+"
    echo '```'
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 2. Kernel Configuration"
    echo ""
    echo "### 2.1 Kernel Command Line"
    echo ""
    echo '```'
    cat /proc/cmdline
    echo '```'
    echo ""
    
    echo "### 2.2 Isolation Parameters"
    echo ""
    echo "| Parameter | Status | Value |"
    echo "|-----------|--------|-------|"
    
    if grep -q "isolcpus=" /proc/cmdline; then
        VALUE=$(grep -o "isolcpus=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| isolcpus | ✓ Enabled | $VALUE |"
    else
        echo "| isolcpus | ✗ Disabled | - |"
    fi
    
    if grep -q "nohz_full=" /proc/cmdline; then
        VALUE=$(grep -o "nohz_full=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| nohz_full | ✓ Enabled | $VALUE |"
    else
        echo "| nohz_full | ✗ Disabled | - |"
    fi
    
    if grep -q "rcu_nocbs=" /proc/cmdline; then
        VALUE=$(grep -o "rcu_nocbs=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| rcu_nocbs | ✓ Enabled | $VALUE |"
    else
        echo "| rcu_nocbs | ✗ Disabled | - |"
    fi
    
    if grep -qE "(intel_iommu=on|amd_iommu=on)" /proc/cmdline; then
        VALUE=$(grep -oE "(intel_iommu|amd_iommu)=[^ ]*" /proc/cmdline | cut -d= -f2)
        echo "| IOMMU | ✓ Enabled | $VALUE |"
    else
        echo "| IOMMU | ✗ Disabled | - |"
    fi
    
    echo ""
    
    echo "### 2.3 CPU Isolation Status"
    echo ""
    if [ -f /sys/devices/system/cpu/isolated ]; then
        ISOLATED=$(cat /sys/devices/system/cpu/isolated)
        if [ -n "$ISOLATED" ]; then
            echo "✓ **Isolated CPUs**: $ISOLATED"
        else
            echo "⚠ **Warning**: No CPUs are isolated"
        fi
    else
        echo "⚠ **Warning**: Isolation status file not found"
    fi
    echo ""
    
    if [ -f /sys/devices/system/cpu/nohz_full ]; then
        NOHZ=$(cat /sys/devices/system/cpu/nohz_full)
        if [ -n "$NOHZ" ]; then
            echo "✓ **NO_HZ Full CPUs**: $NOHZ"
        fi
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 3. IOMMU Configuration"
    echo ""
    echo "### 3.1 IOMMU Status"
    echo ""
    
    if [ -d /sys/kernel/iommu_groups ]; then
        GROUP_COUNT=$(find /sys/kernel/iommu_groups -maxdepth 1 -type d | wc -l)
        GROUP_COUNT=$((GROUP_COUNT - 1))
        
        if [ $GROUP_COUNT -gt 0 ]; then
            echo "✓ **IOMMU Groups Found**: $GROUP_COUNT groups"
            echo ""
            echo "### 3.2 IOMMU Groups (sample)"
            echo ""
            echo '```'
            for group in $(find /sys/kernel/iommu_groups -maxdepth 1 -type d -name "[0-9]*" | sort -V | head -10); do
                group_num=$(basename "$group")
                echo "Group $group_num:"
                for device in "$group"/devices/*; do
                    if [ -e "$device" ]; then
                        dev_path=$(basename "$device")
                        lspci -nn -s "$dev_path" 2>/dev/null | sed 's/^/  /' || echo "  $dev_path"
                    fi
                done
            done
            echo '```'
            echo ""
        else
            echo "⚠ **Warning**: No IOMMU groups found"
            echo ""
        fi
    else
        echo "✗ **Error**: IOMMU not active"
        echo ""
    fi
    
    echo "### 3.3 Network Devices for Passthrough"
    echo ""
    echo '```'
    lspci -nn | grep -i ethernet || echo "No Ethernet devices found"
    echo '```'
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 4. Hypervisor Status"
    echo ""
    echo "### 4.1 Xen Hypervisor"
    echo ""
    
    if command -v xl &> /dev/null; then
        echo "✓ Xen tools installed"
        echo ""
        
        if xl info &> /dev/null; then
            echo "✓ **Xen Status**: Running"
            echo ""
            echo '```'
            xl info | grep -E "^(release|version|xen_caps|virt_caps|total_memory|free_memory|nr_cpus|sched_id):"
            echo '```'
            echo ""
            
            echo "**Scheduler**:"
            echo '```'
            xl info | grep -i sched
            echo '```'
            echo ""
            
            echo "**Dom0 vCPUs**:"
            echo '```'
            xl vcpu-list 0 2>/dev/null || echo "Cannot list vCPUs"
            echo '```'
            echo ""
        else
            echo "⚠ **Xen Status**: Not running (reboot may be needed)"
            echo ""
        fi
    else
        echo "⚠ **Xen Status**: Not installed"
        echo ""
    fi
    
    echo "### 4.2 Intel ACRN"
    echo ""
    if [ -d /sys/module/acrn ] || [ -f /dev/acrn_hsm ] || [ -f /dev/acrn_hvlog ]; then
        echo "✓ **ACRN Status**: Detected"
        echo ""
    else
        echo "⚠ **ACRN Status**: Not detected"
        echo ""
    fi
    
    echo "---"
    echo ""
    
    echo "## 5. IRQ Affinity Configuration"
    echo ""
    echo "### 5.1 IRQ Balancer Status"
    echo ""
    echo '```'
    systemctl status irqbalance --no-pager | head -5 || echo "irqbalance status unknown"
    echo '```'
    echo ""
    
    echo "### 5.2 IRQ Affinity Sample (first 20 IRQs)"
    echo ""
    echo "| IRQ | CPU Affinity | Device |"
    echo "|-----|--------------|--------|"
    
    for irq in $(ls /proc/irq/ | grep "^[0-9]" | head -20); do
        if [ -f "/proc/irq/$irq/smp_affinity_list" ]; then
            affinity=$(cat "/proc/irq/$irq/smp_affinity_list" 2>/dev/null || echo "N/A")
            
            if [ -f "/proc/irq/$irq/actions" ]; then
                actions=$(cat "/proc/irq/$irq/actions" 2>/dev/null | tr '\n' ',' | sed 's/,$//')
            else
                actions=""
            fi
            
            echo "| $irq | $affinity | ${actions:-N/A} |"
        fi
    done
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 6. Verification Results"
    echo ""
    
    TOTAL_CHECKS=0
    PASSED_CHECKS=0
    FAILED_CHECKS=0
    
    echo "### 6.1 CPU Isolation"
    ((TOTAL_CHECKS++))
    if grep -q "isolcpus" /proc/cmdline && [ -f /sys/devices/system/cpu/isolated ] && [ -n "$(cat /sys/devices/system/cpu/isolated)" ]; then
        echo "✓ **PASS**: CPU isolation configured and active"
        ((PASSED_CHECKS++))
    else
        echo "✗ **FAIL**: CPU isolation not properly configured"
        ((FAILED_CHECKS++))
    fi
    echo ""
    
    echo "### 6.2 IOMMU/VT-d"
    ((TOTAL_CHECKS++))
    if grep -qE "(intel_iommu=on|amd_iommu=on)" /proc/cmdline && [ -d /sys/kernel/iommu_groups ]; then
        GROUP_COUNT=$(find /sys/kernel/iommu_groups -maxdepth 1 -type d | wc -l)
        GROUP_COUNT=$((GROUP_COUNT - 1))
        if [ $GROUP_COUNT -gt 0 ]; then
            echo "✓ **PASS**: IOMMU enabled with $GROUP_COUNT groups"
            ((PASSED_CHECKS++))
        else
            echo "✗ **FAIL**: IOMMU enabled but no groups found"
            ((FAILED_CHECKS++))
        fi
    else
        echo "✗ **FAIL**: IOMMU not enabled"
        ((FAILED_CHECKS++))
    fi
    echo ""
    
    echo "### 6.3 Hypervisor Installation"
    ((TOTAL_CHECKS++))
    if command -v xl &> /dev/null && [ -d /etc/xen ]; then
        echo "✓ **PASS**: Xen hypervisor installed"
        ((PASSED_CHECKS++))
    else
        echo "⚠ **PARTIAL**: Hypervisor installation incomplete"
        ((FAILED_CHECKS++))
    fi
    echo ""
    
    echo "### 6.4 RT Tuning Parameters"
    ((TOTAL_CHECKS++))
    if grep -q "nohz_full" /proc/cmdline && grep -q "rcu_nocbs" /proc/cmdline; then
        echo "✓ **PASS**: RT kernel parameters applied"
        ((PASSED_CHECKS++))
    else
        echo "✗ **FAIL**: RT kernel parameters missing"
        ((FAILED_CHECKS++))
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 7. Summary"
    echo ""
    echo "### Verification Score"
    echo ""
    PERCENTAGE=$((PASSED_CHECKS * 100 / TOTAL_CHECKS))
    echo "**Result**: $PASSED_CHECKS / $TOTAL_CHECKS checks passed ($PERCENTAGE%)"
    echo ""
    
    if [ $PERCENTAGE -ge 75 ]; then
        echo "### ✓ Milestone 1: **PASS**"
        echo ""
        echo "The system is properly configured for real-time hypervisor operation."
        echo "CPU isolation, IOMMU, and hypervisor installation are verified."
    elif [ $PERCENTAGE -ge 50 ]; then
        echo "### ⚠ Milestone 1: **PARTIAL**"
        echo ""
        echo "The system has some required configurations but is incomplete."
        echo "Review failed checks and complete missing steps."
    else
        echo "### ✗ Milestone 1: **FAIL**"
        echo ""
        echo "The system does not meet minimum requirements for Milestone 1."
        echo "Significant configuration work is needed."
    fi
    echo ""
    
    echo "### Next Steps"
    echo ""
    if [ $PERCENTAGE -ge 75 ]; then
        echo "1. Proceed to Milestone 2: VM Configuration"
        echo "2. Create RT guest VM with pinned CPUs"
        echo "3. Create GPOS guest VM"
        echo "4. Configure VFIO device passthrough"
    else
        echo "1. Review failed verification checks"
        echo "2. Re-run configuration scripts as needed"
        echo "3. Ensure system reboots with updated parameters"
        echo "4. Re-run verification scripts"
    fi
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 8. Log Files Reference"
    echo ""
    echo "All detailed logs are available in the \`logs/\` directory:"
    echo ""
    for log in "$LOG_DIR"/*.log; do
        if [ -f "$log" ]; then
            filename=$(basename "$log")
            size=$(du -h "$log" | cut -f1)
            echo "- \`$filename\` ($size)"
        fi
    done
    echo ""
    
    echo "---"
    echo ""
    
    echo "## 9. Configuration Files"
    echo ""
    echo "Generated configuration files in \`configs/\` directory:"
    echo ""
    if [ -d "$PROJECT_ROOT/configs" ]; then
        find "$PROJECT_ROOT/configs" -type f -exec basename {} \; | while read -r file; do
            echo "- \`$file\`"
        done
    fi
    echo ""
    
    echo "---"
    echo ""
    echo "*End of Report*"
    echo ""
    
} > "$REPORT_FILE"

echo "✓ Milestone 1 report generated successfully"
echo "✓ Output saved to: $REPORT_FILE"
echo ""
echo "Report preview:"
grep "^#" "$REPORT_FILE" | head -20
echo ""
echo "View full report: cat $REPORT_FILE"
echo ""

